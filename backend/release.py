"""Public playback policy. Only fixed registry entries can become frame origins."""
from __future__ import annotations

import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION = "0.4.0-rc.1"
REGISTRY = json.loads((ROOT / "frontend" / "provider-registry.json").read_text(encoding="utf-8"))


def deployment_info() -> dict:
    """Expose only public revision identity, never a dump of hosting environment."""
    commit = os.environ.get("RENDER_GIT_COMMIT", "")
    return {"release": VERSION, "commit": commit.lower() if re.fullmatch(r"[0-9a-fA-F]{40}", commit) else None}


def playback_config(value: str | None = None) -> dict:
    """Unset enables the registry; an explicitly empty environment value disables all.

    Operational settings use the process environment, including static export in CI.
    The private .env remains reserved for the catalogue's credentials/cache settings.
    """
    keys = [p["key"] for p in REGISTRY]
    value = os.environ.get("CINEMAGIC_PROVIDERS") if value is None else value
    enabled = keys if value is None else [s.strip() for s in value.split(",") if s.strip()]
    if len(enabled) != len(set(enabled)) or any(key not in keys for key in enabled):
        raise ValueError("CINEMAGIC_PROVIDERS must contain unique registry IDs: " + ",".join(keys))
    return {"version": 1, "release": VERSION, "registry": REGISTRY, "enabled": enabled}


def frame_policy(config: dict) -> str:
    origins = [p["origin"] for p in config["registry"] if p["key"] in config["enabled"]]
    # Trailer and same-origin frames remain usable when movie sources are disabled.
    return "frame-src 'self' https://www.youtube-nocookie.com" + (" " + " ".join(origins) if origins else "") + "; object-src 'none'; base-uri 'self'"


def playback_script(config: dict) -> str:
    """Same synchronous bootstrap for FastAPI and the exported static demo.

    The meta policy applies to static hosts too, before the app creates any frames.
    Backend headers additionally protect HTML responses before scripts execute.
    """
    value = json.dumps(config, ensure_ascii=True, separators=(",", ":"))
    policy = json.dumps(frame_policy(config))
    return ("/* Generated by scripts/export_static.py; no credentials. */\n"
            "(function(root){\nconst config=" + value + ";\n"
            "if(typeof module!=='undefined'&&module.exports) module.exports=config;\n"
            "root.CinemagicPlaybackConfig=config;\n"
            "if(root.document){const meta=document.createElement('meta');"
            "meta.httpEquiv='Content-Security-Policy';meta.content=" + policy + ";document.head.append(meta);}\n"
            "})(typeof globalThis!=='undefined'?globalThis:window);\n")
